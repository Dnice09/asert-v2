-- Forms table - Stores form definitions
CREATE TABLE forms
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid               UUID                                    NOT NULL,
    created_at         TIMESTAMP WITHOUT TIME ZONE,
    created_by         VARCHAR(255),
    updated_at         TIMESTAMP WITHOUT TIME ZONE,
    updated_by         VARCHAR(255),
    is_deleted         BOOLEAN,
    name               VARCHAR(255)                            NOT NULL,
    description        TEXT,
    CONSTRAINT pk_forms PRIMARY KEY (id)
);
ALTER TABLE forms
    ADD CONSTRAINT uc_forms_uuid UNIQUE (uuid);

-- Form Sections table - Stores sections within forms
CREATE TABLE form_sections
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid               UUID                                    NOT NULL,
    created_at         TIMESTAMP WITHOUT TIME ZONE,
    created_by         VARCHAR(255),
    updated_at         TIMESTAMP WITHOUT TIME ZONE,
    updated_by         VARCHAR(255),
    is_deleted         BOOLEAN,
    title              VARCHAR(255)                            NOT NULL,
    order_index        INTEGER                                 NOT NULL,
    form_id            BIGINT                                  NOT NULL,
    CONSTRAINT pk_form_sections PRIMARY KEY (id),
    CONSTRAINT fk_form_sections_forms FOREIGN KEY (form_id) REFERENCES forms (id)
);
ALTER TABLE form_sections
    ADD CONSTRAINT uc_form_sections_uuid UNIQUE (uuid);

-- Form Fields table - Stores fields within sections
CREATE TABLE form_fields
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid               UUID                                    NOT NULL,
    created_at         TIMESTAMP WITHOUT TIME ZONE,
    created_by         VARCHAR(255),
    updated_at         TIMESTAMP WITHOUT TIME ZONE,
    updated_by         VARCHAR(255),
    is_deleted         BOOLEAN,
    label              VARCHAR(255)                            NOT NULL,
    field_type         VARCHAR(50)                             NOT NULL,
    required           BOOLEAN                                 NOT NULL DEFAULT FALSE,
    placeholder        VARCHAR(255),
    help_text          VARCHAR(255),
    order_index        INTEGER                                 NOT NULL,
    validation_rules   TEXT,
    section_id         BIGINT                                  NOT NULL,
    CONSTRAINT pk_form_fields PRIMARY KEY (id),
    CONSTRAINT fk_form_fields_sections FOREIGN KEY (section_id) REFERENCES form_sections (id)
);
ALTER TABLE form_fields
    ADD CONSTRAINT uc_form_fields_uuid UNIQUE (uuid);

