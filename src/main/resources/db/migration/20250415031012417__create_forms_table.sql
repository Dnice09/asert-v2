    field_id           BIGINT                                  NOT NULL,
    CONSTRAINT pk_form_field_options PRIMARY KEY (id),
    CONSTRAINT fk_form_field_options_fields FOREIGN KEY (field_id) REFERENCES form_fields (id)
);
ALTER TABLE form_field_options
    ADD CONSTRAINT uc_form_field_options_uuid UNIQUE (uuid);

