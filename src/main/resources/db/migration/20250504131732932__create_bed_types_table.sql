-- Step 1: Create bed_types table
CREATE TABLE IF NOT EXISTS bed_types
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid        UUID                                    NOT NULL,
    created_at  TIMESTAMP WITHOUT TIME ZONE,
    created_by  VARCHAR(255),
    updated_at  TIMESTAMP WITHOUT TIME ZONE,
    updated_by  VARCHAR(255),
    is_deleted  BOOLEAN DEFAULT FALSE,
    version     BIGINT                                  NOT NULL,
    name        VARCHAR(255)                            NOT NULL,
    description TEXT,
    CONSTRAINT pk_bed_types PRIMARY KEY (id),
    CONSTRAINT uc_bed_types_uuid UNIQUE (uuid)
);

-- Step 2: Add bed_type_id to room_types
ALTER TABLE room_types
    ADD COLUMN IF NOT EXISTS bed_type_id BIGINT;

ALTER TABLE room_types
    ADD CONSTRAINT fk_room_types_bed_type_id
        FOREIGN KEY (bed_type_id)
            REFERENCES bed_types (id);

