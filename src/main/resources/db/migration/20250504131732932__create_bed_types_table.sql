-- Step 4: Update room_types to set bed_type_id based on string match
UPDATE room_types rt
SET bed_type_id = bt.id
FROM bed_types bt
WHERE UPPER(rt.bed_type) = bt.name
  AND rt.bed_type_id IS NULL;

